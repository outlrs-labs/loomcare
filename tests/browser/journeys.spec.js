test('uncancelled fall, reminder button and low battery',async({page,context})=>{
  await onboard(page);
  const gateway=await pair(page,context);
  await gateway.getByRole('button',{name:'Simulate possible fall'}).click();
  await expect.poll(async()=>{const state=await apiState(page);return state.events.filter(e=>e.kind==='fall').length;},{timeout:22000}).toBe(1);
  await gateway.getByRole('button',{name:'Battery 12%'}).click();
  await expect.poll(async()=>{const state=await apiState(page);return state.events.filter(e=>e.kind==='low_battery').length;}).toBe(1);
  await page.bringToFront();
  await page.getByRole('button',{name:'+ Reminder',exact:true}).click();
  await page.getByLabel('Reminder label').fill('Test daily reminder');
  const time=new Date().toLocaleTimeString('en-GB',{timeZone:'Asia/Kolkata',hour:'2-digit',minute:'2-digit',hour12:false});
  await page.getByLabel('Time · India Standard Time').fill(time);
  await page.getByRole('button',{name:'Save reminder'}).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await gateway.bringToFront();
  await expect(gateway.getByText('Test daily reminder',{exact:true})).toBeVisible({timeout:15000});
  await gateway.getByRole('button',{name:'I’m okay / acknowledge'}).click();
  await expect.poll(async()=>{const state=await apiState(page);return state.events.find(e=>e.kind==='reminder')?.status;}).toBe('acknowledged');
});

