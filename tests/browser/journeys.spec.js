  expect((await apiState(page)).events.filter(e=>e.kind==='sos')).toHaveLength(0);
  await gateway.getByRole('button',{name:'Restore internet'}).click();
  await expect(gateway.locator('#queue-count')).toHaveText('0');
  await expect.poll(async()=>{const state=await apiState(page);return state.events.filter(e=>e.kind==='sos').length;}).toBe(1);
  await page.bringToFront();
  await page.reload();
  await expect(page.getByText('1 critical alert needs attention.')).toBeVisible();
